
SELECT EMPNO, ENAME, DEPTNO
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM EMP
    WHERE ENAME = 'SCOTT'
);

SELECT EMPNO, ENAME, SAL
FROM EMP
WHERE SAL >
(
    SELECT AVG(SAL)
    FROM EMP
);

SELECT E.ENAME, E.JOB
FROM EMP E
WHERE EXISTS
(
    SELECT 1
    FROM EMP X
    WHERE X.MGR = E.EMPNO
);


SELECT EMPNO, ENAME, SAL
FROM EMP
WHERE SAL < ALL
(
    SELECT SAL
    FROM EMP
    WHERE DEPTNO = 10
);


SELECT EMPNO, ENAME, DEPTNO, MGR
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM EMP
    WHERE ENAME = 'SCOTT'
)
AND MGR =
(
    SELECT MGR
    FROM EMP
    WHERE ENAME = 'SCOTT'
)
AND ENAME <> 'SCOTT';


SELECT EMPNO, ENAME
FROM EMP
WHERE DEPTNO IN
(
    SELECT DEPTNO
    FROM EMP
    WHERE ENAME LIKE '%R%'
);


SELECT ENAME, DEPTNO, JOB
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM DEPT
    WHERE LOC = 'NEW YORK'
);



ACCEPT P_LOC CHAR PROMPT 'Enter Location: '

SELECT ENAME, DEPTNO, JOB
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM DEPT
    WHERE UPPER(LOC) = UPPER('&P_LOC')
);

